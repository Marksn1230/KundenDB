delete process.env.DATABASE_URL;
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { mkdtempSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { db, all, get } from '../lib/db';
test('Bestandsmigration erhält Nummer, Stammdaten und Zahlung; entfernt Erstellungsdatum und gesondertes Anbieter-Zahlungsfeld', async () => {
    const dir = mkdtempSync(path.join(tmpdir(), 'kundenraum-migration-'));
    process.env.DATABASE_PATH = path.join(dir, 'legacy.sqlite');
    const legacy = new DatabaseSync(process.env.DATABASE_PATH);
    legacy.exec(`CREATE TABLE customers(id INTEGER PRIMARY KEY,name TEXT,customer_number TEXT,phone TEXT,postal_code TEXT,address TEXT,mac_address TEXT,created_at TEXT,provider TEXT,assignee TEXT,points REAL,comment TEXT,service_start TEXT,service_end TEXT,package_months INTEGER,payment_status TEXT,due_date TEXT,art_paid INTEGER);
  INSERT INTO customers VALUES(12,'Bestand','K-000012','+436640000000','00123','Fiktiv','02:00:00:00:99:01','2025-01-01','Art','Mirko',1.5,'Erhalten','2026-01-31','2026-07-31',6,'Unbezahlt','2026-02-01',1);
  CREATE TABLE sessions(token_hash TEXT);INSERT INTO sessions VALUES('old-session');PRAGMA user_version=1;`);
    legacy.close();
    db();
    const c = (await get('SELECT * FROM customers WHERE id=12'))!, p = (await get('SELECT * FROM periods WHERE customer_id=12'))!;
    assert.equal(c.customer_number, 'K-000012');
    assert.equal(c.postal_code, '00123');
    assert.equal(c.provider, 'Art');
    assert.equal(c.points, 1.5);
    assert.equal(c.comment, 'Erhalten');
    assert.equal(p.payment_status, 'Unbezahlt');
    assert.equal(p.due_date, '2026-02-01');
    assert.equal(p.service_end, '2026-07-31');
    const cols = (await all('PRAGMA table_info(customers)')).map(r => r.name);
    assert.equal(cols.includes('created_at'), false);
    assert.equal(cols.includes('art_paid'), false);
    assert.equal((await all('SELECT * FROM sessions')).length, 0);
    assert.equal(readdirSync(dir).filter(f => f.endsWith('.bak')).length, 3);
});
