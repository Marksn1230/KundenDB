test('MGMT: bereits vorhanden, Ende geändert, neu und Konflikt; Vorschau schreibt keine Konten', async () => {
    const c = await make('  Alpha  ', '02-00-00-00-02-01');
    await make('Beta', '02:00:00:00:02:02');
    const before = (await everyCustomer()).length;
    const p = await makePreview(mgmt([{ Name: 'ALPHA', MAC: '020000000201', Ende: '28.02.2026' }, { Name: ' beta ', MAC: '02-00-00-00-02-02', Ende: '31.12.2026' }, { Name: 'Gamma', MAC: '02:00:00:00:02:03', Ende: '31.12.2026' }, { Name: 'Nummer', MAC: '02:00:00:00:02:04', Ende: '31.12.2026' }]), actor);
    assert.deepEqual(p.counts, { existing: 1, changed: 1, new: 1, review: 1, unmatched: 0 });
    assert.equal(p.rows[0].customer_number, c.customer_number);
    assert.equal((await everyCustomer()).length, before);
    const skip = await commitImport({ preview_id: p.id, selection: [] }, actor);
    assert.equal(skip.created, 0);
    assert.equal((await everyCustomer()).length, before);
    const fresh = await makePreview(mgmt([{ Name: 'Gamma', MAC: '02:00:00:00:02:03', Ende: '31.12.2026' }]), actor);
    const result = await commitImport({ preview_id: fresh.id, selection: [{ index: 0, payment: 'keep' }] }, actor);
    assert.equal(result.created, 1);
    const gamma = (await everyCustomer()).find(c => c.name === 'Gamma')!;
    assert.equal(gamma.payment_status, 'Unbekannt');
    assert.equal(gamma.needs_completion, true);
    assert.equal(gamma.due_date, null);
    assert.match(gamma.customer_number, /^[A-Z0-9]{6}$/);
    assert.deepEqual(await commitImport({ preview_id: fresh.id, selection: [{ index: 0, payment: 'keep' }] }, actor), result);
    assert.equal((await makePreview(mgmt([{ Name: 'Gamma', MAC: '02:00:00:00:02:03', Ende: '31.12.2026' }]), actor)).counts.existing, 1);
});
test('Import: Verlängerung erhält Zahlungsdaten; Wiederholung erzeugt keine Zeiträume oder Statusänderung', async () => {
    const c = await make('Verlängerung', '02:00:00:00:03:01');
    const req = mgmt([{ Name: c.name, MAC: c.mac_address, Ende: '31.12.2026' }]);
    const p = await makePreview(req, actor);
    await commitImport({ preview_id: p.id, selection: [{ index: 0, payment: 'unpaid' }] }, actor);
    const current = await customer(c.id);
    assert.equal(current.customer_number, c.customer_number);
    assert.equal(current.payment_status, 'Unbezahlt');
    assert.equal(current.service_start, c.service_end);
    const history = await all('SELECT * FROM periods WHERE customer_id=? ORDER BY id', c.id);
    assert.equal(history.length, 2);
    assert.equal(history[0].payment_status, 'Bezahlt');
    assert.equal(history[0].is_current, 0);
    const repeated = await makePreview(req, actor);
    assert.equal(repeated.counts.existing, 1);
    await commitImport({ preview_id: repeated.id, selection: [{ index: 0, payment: 'unpaid' }] }, actor);
    assert.equal((await all('SELECT * FROM periods WHERE customer_id=?', c.id)).length, 2);
    assert.equal((await customer(c.id)).version, current.version);
    await transaction(async () => await updateCustomer(c.id, { comment: 'Nur Kommentar geändert' }, current.version, actor));
    assert.equal((await customer(c.id)).service_end, '2026-12-31');
});
