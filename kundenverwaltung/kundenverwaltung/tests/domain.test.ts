test('CSV/XLSX: führende Nullen, Datumswerte, serverseitige Größen- und Formelgrenzen', async () => {
    const csv = await readImport(new File(['Name;MAC;PLZ\r\nFiktiv;020000000601;00123'], 'liste.csv'));
    assert.equal(csv.rows[0].PLZ, '00123');
    const workbook = new ExcelJS.Workbook(), sheet = workbook.addWorksheet('Kunden');
    sheet.addRow(['Name', 'MAC', 'PLZ', 'Ende']);
    sheet.addRow(['Fiktiv', '020000000602', '00123', new Date('2026-12-31T00:00:00Z')]);
    const buffer = await workbook.xlsx.writeBuffer();
    const file = new File([new Uint8Array(buffer)], 'liste.xlsx');
    const excel = await readImport(file);
    assert.equal(excel.rows[0].PLZ, '00123');
    assert.equal(excel.rows[0].Ende, '2026-12-31');
    sheet.getCell('A2').value = { formula: '1+1', result: 2 };
    await assert.rejects(readImport(new File([new Uint8Array(await workbook.xlsx.writeBuffer())], 'formel.xlsx')), /Formeln/);
    await assert.rejects(readImport(new File(['x'.repeat(5 * 1024 * 1024 + 1)], 'gross.csv')), /5 MB/);
});
